"""The run ledger (spec §30) -- the only place wall-clock time is allowed.

Reports must be byte-identical between two runs over the same input, so no
timestamp may reach a report.  Cost, duration and cache telemetry still have to
be recorded somewhere, and that somewhere is here: a per-run ledger file that
nothing hashes, asserts or diffs.

``new_run_id`` is intentionally **not** deterministic -- two runs are two runs
-- which is exactly why the run id lives in the ledger and is passed into the
report by the caller rather than generated by a report renderer.
"""

from __future__ import annotations

import math
import os
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Optional

from ..util import read_json, short_hash, write_json


@dataclass
class ToolTiming:
    provider: str
    duration_ms: int = 0
    status: str = "OK"

    def to_dict(self) -> dict[str, Any]:
        return {
            "provider": self.provider,
            "duration_ms": self.duration_ms,
            "status": self.status,
        }


@dataclass
class RunLedger:
    run_id: str = ""
    repo: str = ""
    commit: Optional[str] = None
    base: Optional[str] = None
    mode: str = "diff"
    started_at: str = ""
    duration_ms: int = 0
    tool_duration: list[ToolTiming] = field(default_factory=list)
    llm_calls: int = 0
    input_tokens: int = 0
    output_tokens: int = 0
    cache_hit: float = 0.0
    findings: int = 0
    dedup_ratio: float = 0.0
    gate: Optional[str] = None
    errors: list[dict[str, Any]] = field(default_factory=list)

    # ------------------------------------------------------------------ api

    def add_tool(self, provider: str, duration_ms: int, status: str) -> None:
        self.tool_duration.append(
            ToolTiming(provider=str(provider), duration_ms=int(duration_ms), status=str(status))
        )

    def add_llm(self, calls: int, input_tokens: int, output_tokens: int) -> None:
        self.llm_calls += int(calls)
        self.input_tokens += int(input_tokens)
        self.output_tokens += int(output_tokens)

    def to_dict(self) -> dict[str, Any]:
        return {
            "run_id": self.run_id,
            "repo": self.repo,
            "commit": self.commit,
            "base": self.base,
            "mode": self.mode,
            "started_at": self.started_at,
            "duration_ms": self.duration_ms,
            "tool_duration": [t.to_dict() for t in self.tool_duration],
            "llm_calls": self.llm_calls,
            "input_tokens": self.input_tokens,
            "output_tokens": self.output_tokens,
            "cache_hit": self.cache_hit,
            "findings": self.findings,
            "dedup_ratio": self.dedup_ratio,
            "gate": self.gate,
            "errors": [dict(e) for e in self.errors],
            "error_count": len(self.errors),
        }

    def write(self, path: Path | str) -> None:
        write_json(path, self.to_dict())


def new_run_id(repo_root: Path | str, *, mode: str, commit: Optional[str]) -> str:
    """A unique, sortable run id.

    Unique -- not deterministic -- because two runs of the same commit must not
    overwrite each other's artefacts.  It is deliberately *not* derived from
    the report content and never feeds a hash or an assertion.
    """
    stamp = time.strftime("%Y%m%dT%H%M%S", time.localtime())
    entropy = short_hash(
        str(repo_root),
        str(mode),
        str(commit or ""),
        str(time.time_ns()),
        str(os.getpid()),
        length=6,
    )
    return f"{stamp}-{entropy}"


