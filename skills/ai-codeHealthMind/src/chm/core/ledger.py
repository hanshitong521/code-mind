def percentile(values: list[float], p: float) -> float:
    """Linear-interpolated percentile; empty input yields 0.0."""
    if not values:
        return 0.0
    xs = sorted(float(v) for v in values)
    if len(xs) == 1:
        return xs[0]
    if p <= 0.0:
        return xs[0]
    if p >= 100.0:
        return xs[-1]
    position = (len(xs) - 1) * (p / 100.0)
    low = int(math.floor(position))
    high = int(math.ceil(position))
    if low == high:
        return xs[low]
    return xs[low] + (xs[high] - xs[low]) * (position - low)


def _round(value: float, digits: int) -> float:
    return round(float(value), digits)


def _ledger_files(directory: Path) -> list[Path]:
    """Ledgers live either flat in the directory or one level down.

    The orchestrator writes ``<run_dir>/<run_id>/ledger.json``, while ad-hoc
    callers write ``<dir>/ledger.json``; both have to be found, and
    ``<runs>/latest.json`` (a pointer, not a ledger) is filtered out later by
    the ``run_id`` check.
    """
    seen: dict[str, Path] = {}
    for pattern in ("*.json", "*/ledger.json", "*/*.json"):
        for candidate in directory.glob(pattern):
            if candidate.is_file():
                seen[str(candidate)] = candidate
    return [seen[k] for k in sorted(seen)]


def summarize_ledgers(ledger_dir: Path | str) -> dict[str, Any]:
    """Aggregate every ledger under a runs directory.

    Degrades honestly: unreadable or malformed ledgers are counted in
    ``skipped`` instead of being silently treated as zero-cost runs.
    """
    directory = Path(ledger_dir)
    ledgers: list[dict[str, Any]] = []
    skipped = 0
    if directory.is_dir():
        for path in _ledger_files(directory):
            data = read_json(path, default=None)
            if isinstance(data, dict) and "run_id" in data:
                ledgers.append(data)
            else:
                skipped += 1

    if not ledgers:
        return {
            "runs": 0,
            "skipped": skipped,
            "avg_input_tokens": 0.0,
            "avg_output_tokens": 0.0,
            "p50_ms": 0.0,
            "p95_ms": 0.0,
            "tool_duration": {},
            "cache_hit_ratio": 0.0,
            "gate_histogram": {},
            "new_debt_per_run": {"avg": 0.0, "total": 0, "per_run": {}},
        }

    durations = [float(x.get("duration_ms", 0) or 0) for x in ledgers]
    inputs = [float(x.get("input_tokens", 0) or 0) for x in ledgers]
    outputs = [float(x.get("output_tokens", 0) or 0) for x in ledgers]
    cache_hits = [float(x.get("cache_hit", 0.0) or 0.0) for x in ledgers]

    tool_samples: dict[str, list[float]] = {}
    for ledger in ledgers:
        for timing in ledger.get("tool_duration") or []:
            if not isinstance(timing, dict):
                continue
            provider = str(timing.get("provider", "unknown"))
            tool_samples.setdefault(provider, []).append(
                float(timing.get("duration_ms", 0) or 0)
            )

    gate_histogram: dict[str, int] = {}
    for ledger in ledgers:
        verdict = ledger.get("gate")
        if verdict is None:
            continue
        gate_histogram[str(verdict)] = gate_histogram.get(str(verdict), 0) + 1

    # The ledger records the post-dedup finding count; with no separate
    # new-debt counter that is the most honest proxy available.
    per_run = {
        str(ledger.get("run_id", "")): int(ledger.get("findings", 0) or 0)
        for ledger in ledgers
    }
    debt_values = list(per_run.values())

    return {
        "runs": len(ledgers),
        "skipped": skipped,
        "avg_input_tokens": _round(sum(inputs) / len(inputs), 1),
        "avg_output_tokens": _round(sum(outputs) / len(outputs), 1),
        "p50_ms": _round(percentile(durations, 50), 1),
        "p95_ms": _round(percentile(durations, 95), 1),
        "tool_duration": {
            provider: {
                "avg_ms": _round(sum(samples) / len(samples), 1),
                "p95_ms": _round(percentile(samples, 95), 1),
                "runs": len(samples),
            }
            for provider, samples in sorted(tool_samples.items())
        },
        "cache_hit_ratio": _round(sum(cache_hits) / len(cache_hits), 4),
        "gate_histogram": dict(sorted(gate_histogram.items())),
        "new_debt_per_run": {
            "avg": _round(sum(debt_values) / len(debt_values), 1),
            "total": sum(debt_values),
            "per_run": dict(sorted(per_run.items())),
        },
    }
